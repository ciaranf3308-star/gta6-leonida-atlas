#!/usr/bin/env node
/**
 * Apply (reconcile) the fbrito card import onto the generated checklist
 * files, or verify them (`--check`), from the committed manifest.
 *
 *   node scripts/apply-fbrito-import.mjs [--check]
 *
 * Reads `scripts/fbrito-import-manifest.json` and reconciles:
 *   - src/data/card-checklist.generated.ts — the 346 imported slots go
 *     `area-known` -> `pinned` with catalogueId `card:fbrito-<id>`; the
 *     12 host-disagreement notes, 4 host B-conflict notes, 11 non-host
 *     held reasons and 2 citation-B notes are appended to the slots'
 *     `conflict` fields (never overwriting an existing note).
 *   - src/data/card-fbrito-pins.generated.ts — rewritten wholesale from
 *     the manifest (346 candidate pins, evidence "approximate").
 *
 * HARD RULES (violations abort, nothing is written):
 *   1. NEVER MOVE A HOST-PINNED SLOT. An imported slot must currently be
 *      `area-known` with no host id and no catalogue pin — unless it is
 *      already applied exactly as the manifest says (idempotent re-run).
 *      A host-pinned slot's placement and catalogueId are never touched;
 *      only a conflict note may be appended to it.
 *   2. No fbrito pin id may collide with an existing catalogue place id.
 *   3. Counts must reconcile: pinned + area-known + unmapped = 480
 *      slots; imported + gap + held(non-host) = 440 non-host slots.
 *
 * Takedown: `node scripts/remove-fbrito-pins.mjs --ids <...>` moves ids
 * to the manifest's `removed` list; re-running this script then removes
 * their pins and restores their slots to `area-known` (and strips the
 * import's conflict notes from those slots). The pins file is always
 * rewritten from the manifest, so removal is complete by construction.
 *
 * If src/data/card-checklist.generated.ts is ever regenerated by
 * scripts/build-card-checklist.mjs, re-run this script afterwards —
 * the generator does not know about the import. The `--check` mode
 * (also exercised by tests/unit/fbrito-import.test.ts) catches drift.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SET_NAMES } from './fbrito-join-lib.mjs';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST_PATH = resolve(repoRoot, 'scripts', 'fbrito-import-manifest.json');
const CHECKLIST_PATH = resolve(repoRoot, 'src', 'data', 'card-checklist.generated.ts');
const PINS_PATH = resolve(repoRoot, 'src', 'data', 'card-fbrito-pins.generated.ts');

export const FBRITO_PIN_PREFIX = 'card:fbrito-';
export function pinIdFor(fbritoId) {
  return `${FBRITO_PIN_PREFIX}${fbritoId}`;
}
export function isFbritoPinId(id) {
  return typeof id === 'string' && id.startsWith(FBRITO_PIN_PREFIX);
}
export function fbritoIdForPinId(id) {
  return isFbritoPinId(id) ? id.slice(FBRITO_PIN_PREFIX.length) : null;
}

/** Active resolved entries (manifest.resolved minus manifest.removed). */
export function activeResolved(manifest) {
  const removed = new Set((manifest.removed ?? []).map((r) => r.fbritoId));
  return manifest.resolved.filter((r) => !removed.has(r.fbritoId));
}

// Conflict notes appended by the import. Every note names the source
// ("Open GTA 6 Map") so a takedown restore can strip exactly these.
export function disagreementNote(d) {
  return `Open GTA 6 Map record ${d.fbritoId} sits ${d.distanceUnits}u from this host pin — host position kept; the fbrito position was not imported.`;
}
export function bConflictNote(b) {
  return `Two Open GTA 6 Map records claim this slot (${b.records.join(', ')}) — held for arbitration; host position kept.`;
}
export function heldNote(h) {
  return `Held from the Open GTA 6 Map import: ${h.reason}`;
}

/**
 * Compute the checklist updates for the manifest, purely.
 * Returns { updates, pins, stats } where updates is a Map slotId ->
 * { placement, catalogueId, appendNotes[], stripNotes[] }.
 * Throws on any hard-rule violation.
 */
export function computeChanges(manifest, items) {
  const byId = new Map(items.map((i) => [i.id, i]));
  const hostPinned = new Set(manifest.hostPinnedSlotIds);
  const updates = new Map();
  const errors = [];
  const get = (slotId) => {
    // catalogueId: undefined = no change, null = restore to null.
    if (!updates.has(slotId)) updates.set(slotId, { placement: null, catalogueId: undefined, appendNotes: [], stripNotes: [] });
    return updates.get(slotId);
  };

  // 1. Imported slots: area-known -> pinned, catalogueId = fbrito pin.
  for (const r of activeResolved(manifest)) {
    const slot = byId.get(r.slotId);
    if (!slot) { errors.push(`resolved slot missing from checklist: ${r.slotId}`); continue; }
    if (hostPinned.has(r.slotId)) { errors.push(`NEVER-MOVE VIOLATION: resolved slot is host-pinned: ${r.slotId}`); continue; }
    if (slot.placement === 'pinned') {
      if (slot.catalogueId === pinIdFor(r.fbritoId) && slot.hostId == null) {
        // Already applied (idempotent re-run) — only notes may be missing.
      } else {
        errors.push(`NEVER-MOVE VIOLATION: slot ${r.slotId} is pinned to ${slot.catalogueId} (host ${slot.hostId ?? 'none'}), not an fbrito pin — refusing to move it`);
        continue;
      }
    } else if (slot.placement !== 'area-known' || slot.hostId != null || slot.catalogueId != null) {
      errors.push(`slot ${r.slotId} is ${slot.placement} with hostId ${slot.hostId ?? 'null'} / catalogueId ${slot.catalogueId ?? 'null'} — expected area-known with neither`);
      continue;
    }
    const u = get(r.slotId);
    u.placement = 'pinned';
    u.catalogueId = pinIdFor(r.fbritoId);
    if (r.conflictNote) u.appendNotes.push(`Open GTA 6 Map import — ${r.conflictNote}`);
  }

  // 2. Held reasons + host disagreements + host B conflicts (notes only).
  for (const h of manifest.held) {
    const slot = byId.get(h.slotId);
    if (!slot) { errors.push(`held slot missing from checklist: ${h.slotId}`); continue; }
    if (h.reason.startsWith('host-pinned')) {
      if (slot.placement !== 'pinned') errors.push(`held host slot ${h.slotId} is not pinned (found ${slot.placement})`);
      get(h.slotId).appendNotes.push(`Open GTA 6 Map import — ${h.reason}`);
    } else {
      get(h.slotId).appendNotes.push(heldNote(h));
    }
  }
  for (const d of manifest.hostDisagreements) {
    // The citation-based ones are already covered by the held reasons
    // above (same fbrito id, same distance); only the name-join-only
    // disagreements need a note built here.
    const covered = manifest.held.some(
      (h) => h.slotId === d.slotId && h.fbritoId === d.fbritoId,
    );
    if (covered) continue;
    const slot = byId.get(d.slotId);
    if (!slot) { errors.push(`disagreement slot missing from checklist: ${d.slotId}`); continue; }
    get(d.slotId).appendNotes.push(`Open GTA 6 Map import — ${disagreementNote(d)}`);
  }
  for (const b of manifest.hostBConflicts) {
    const slot = byId.get(b.slotId);
    if (!slot) { errors.push(`B-conflict slot missing from checklist: ${b.slotId}`); continue; }
    get(b.slotId).appendNotes.push(`Open GTA 6 Map import — ${bConflictNote(b)}`);
  }

  // 3. Takedown restores: slots pointing at fbrito pins that are no
  // longer active (removed) go back to area-known.
  const activeIds = new Set(activeResolved(manifest).map((r) => r.slotId));
  const removedBySlot = new Map((manifest.removed ?? []).map((r) => [r.slotId, r]));
  for (const item of items) {
    if (!isFbritoPinId(item.catalogueId)) continue;
    if (activeIds.has(item.id)) continue;
    const tomb = removedBySlot.get(item.id);
    if (!tomb) { errors.push(`slot ${item.id} points at fbrito pin ${item.catalogueId} but is in neither resolved nor removed — refusing to guess`); continue; }
    const u = get(item.id);
    u.placement = 'area-known';
    u.catalogueId = null;
    // Strip exactly the notes this import appended (reverse append order:
    // they were appended as suffixes, so strip from the end).
    u.stripNotes = notesForSlot(manifest, tomb);
  }

  if (errors.length) throw new Error(`fbrito import aborted:\n- ${errors.join('\n- ')}`);

  // Pins: one per active resolved entry, in manifest order.
  const pins = activeResolved(manifest).map((r) => pinFor(r, byId.get(r.slotId)));

  // Counts must reconcile.
  const after = items.map((i) => {
    const u = updates.get(i.id);
    return u?.placement ? { ...i, placement: u.placement } : i;
  });
  const pinned = after.filter((i) => i.checklistSlot && i.placement === 'pinned').length;
  const areaKnown = after.filter((i) => i.checklistSlot && i.placement === 'area-known').length;
  const unmapped = after.filter((i) => i.checklistSlot && i.placement === 'unmapped').length;
  const stats = { pinned, areaKnown, unmapped, pins: pins.length };
  if (pinned + areaKnown + unmapped !== 480) {
    throw new Error(`counts do not reconcile: pinned ${pinned} + area-known ${areaKnown} + unmapped ${unmapped} != 480`);
  }
  if (pins.length + manifest.gap.length + manifest.held.filter((h) => !h.reason.startsWith('host-pinned')).length + (manifest.removed ?? []).length !== 440) {
    throw new Error('counts do not reconcile: imported + gap + non-host held + removed != 440');
  }
  return { updates, pins, stats };
}

/** The exact notes the import would have appended for a (removed) slot. */
export function notesForSlot(manifest, resolvedEntry) {
  const notes = [];
  if (resolvedEntry.conflictNote) notes.push(`Open GTA 6 Map import — ${resolvedEntry.conflictNote}`);
  for (const h of manifest.held.filter((x) => x.slotId === resolvedEntry.slotId)) {
    notes.push(h.reason.startsWith('host-pinned') ? `Open GTA 6 Map import — ${h.reason}` : heldNote(h));
  }
  for (const d of manifest.hostDisagreements.filter((x) => x.slotId === resolvedEntry.slotId)) {
    const covered = manifest.held.some((h) => h.slotId === d.slotId && h.fbritoId === d.fbritoId);
    if (!covered) notes.push(`Open GTA 6 Map import — ${disagreementNote(d)}`);
  }
  for (const b of manifest.hostBConflicts.filter((x) => x.slotId === resolvedEntry.slotId)) {
    notes.push(`Open GTA 6 Map import — ${bConflictNote(b)}`);
  }
  return notes;
}

export function pinFor(entry, slot) {
  const setName = SET_NAMES[entry.setId] ?? entry.setId;
  return {
    id: pinIdFor(entry.fbritoId),
    title: `${entry.person} (${entry.variant}) — ${setName}`,
    description: `Collectible card, ${setName} set. ${slot.spotDescription} Pin is a candidate position from the Open GTA 6 Map (fbritoferreira, CC BY 4.0), converted from its map coordinates — not a verified building position.`,
    category: 'collectibles',
    position: entry.position,
    layerId: `cards:${entry.setId}`,
    tags: ['collectible', 'trading-card', entry.setId, 'card', 'fbrito-import'],
    region: slot.areaLead,
    source: { title: 'Open GTA 6 Map (fbritoferreira) · CC BY 4.0', url: entry.sourceUrl },
    evidence: 'approximate',
  };
}

